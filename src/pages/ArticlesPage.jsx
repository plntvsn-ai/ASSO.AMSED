import React, { useState, useEffect } from 'react';
import { Link } from 'react-router-dom';
import { useCms } from '../context/CmsContext';
import { useLanguage } from '../context/LanguageContext';
import { Navbar } from '../components/Navbar';
import { Footer } from '../components/Footer';
import { 
  Calendar, User, Tag, Search, ArrowLeft, 
  FileText, ArrowRight, Sparkles, ExternalLink, Rss 
} from 'lucide-react';
import { getTopicMatchedImage } from '../services/topicImageService';

import { AutismScreeningModal } from '../components/AutismScreeningModal';

export const ArticlesPage = () => {
  const { cmsData } = useCms();
  const { lang, dir, getLocalized } = useLanguage();
  const [searchTerm, setSearchTerm] = useState('');
  const [selectedCategory, setSelectedCategory] = useState('all');
  const [rssArticles, setRssArticles] = useState([]);
  const [screeningOpen, setScreeningOpen] = useState(false);

  useEffect(() => {
    fetch('/api/news')
      .then(res => {
        if (!res.ok || !res.headers.get('content-type')?.includes('application/json')) return null;
        return res.json();
      })
      .then(data => {
        if (!data) return;
        const list = Array.isArray(data) ? data : (data?.news || []);
        if (list.length > 0) {
          setRssArticles(list);
        }
      })
      .catch(err => console.warn('RSS news fetch notice:', err));
  }, []);

  const localArticles = (cmsData.articles || []).filter(a => a.published !== false);

  const formattedRssArticles = rssArticles.map(item => ({
    id: item.id,
    title: item.title,
    content: item.summary || item.rawTitle || item.title,
    createdAt: item.formattedDate || item.pubDate,
    author: item.source || 'Google News RSS',
    category: 'أخبار وطنية (RSS)',
    image: item.image,
    link: item.link,
    source: item.source,
    isRss: true
  }));

  const allCombined = [...localArticles, ...formattedRssArticles];

  const categoryLabels = {
    "all": { ar: "الكل", fr: "Tous", en: "All" },
    "مقالات وبحوث تربوية": { ar: "مقالات وبحوث تربوية", fr: "Articles & Recherches", en: "Educational Articles" },
    "التوحد والطفولة": { ar: "التوحد والطفولة", fr: "Autisme & Enfance", en: "Autism & Childhood" },
    "أخبار الجمعية": { ar: "أخبار الجمعية", fr: "Actualités AMSED", en: "AMSED News" },
    "التعليم والإدماج": { ar: "التعليم والإدماج", fr: "Éducation & Inclusion", en: "Education & Inclusion" },
    "التأهيل المهني": { ar: "التأهيل المهني", fr: "Formation Professionnelle", en: "Vocational Training" },
    "أنشطة وترفيه": { ar: "أنشطة وترفيه", fr: "Activités & Loisirs", en: "Activities & Leisure" },
    "قوافل ومبادرات": { ar: "قوافل ومبادرات", fr: "Caravanes & Initiatives", en: "Caravans & Initiatives" },
    "أخبار وطنية (RSS)": { ar: "أخبار وطنية (RSS)", fr: "Presse Nationale (RSS)", en: "National News (RSS)" }
  };

  const categories = [
    "all", 
    "مقالات وبحوث تربوية",
    "التوحد والطفولة",
    "أخبار الجمعية", 
    "التعليم والإدماج", 
    "التأهيل المهني", 
    "أنشطة وترفيه", 
    "قوافل ومبادرات", 
    "أخبار وطنية (RSS)"
  ];

  const filtered = allCombined.filter(art => {
    const titleLocalized = getLocalized(art, 'title') || art.title || '';
    const contentLocalized = getLocalized(art, 'content') || art.content || '';
    const matchesSearch = titleLocalized.toLowerCase().includes(searchTerm.toLowerCase()) || 
                          contentLocalized.toLowerCase().includes(searchTerm.toLowerCase());
    const isSpecialArt = Boolean(art.is_ai || art.autoGenerated || art.category === 'التوحد والطفولة');
    const matchesCat = selectedCategory === 'all' || 
      (selectedCategory === 'مقالات وبحوث تربوية' ? isSpecialArt : art.category === selectedCategory);
    return matchesSearch && matchesCat;
  });

  return (
    <div className="min-h-screen flex flex-col moroccan-zellij-bg font-sans text-slate-800" dir={dir}>
      <Navbar />

      <main className="flex-1 py-12">
        <div className="max-w-7xl mx-auto px-4 sm:px-6 space-y-10">
          
          {/* Header */}
          <div className="text-center max-w-3xl mx-auto space-y-3">
            <div className="inline-flex items-center gap-2 px-3.5 py-1 rounded-full bg-emerald-100 text-emerald-800 text-xs font-bold border border-emerald-200">
              <FileText className="w-3.5 h-3.5 text-emerald-700" />
              <span>
                {lang === 'ar' ? 'مستجدات وبلاغات الجمعية والصحافة الوطنية' : lang === 'fr' ? 'Actualités, Communiqués et Presse' : 'News, Releases and Press'}
              </span>
            </div>
            <h1 className="text-3xl sm:text-4xl font-black text-slate-900 tracking-tight">
              {lang === 'ar' ? 'المقالات، البلاغات والأخبار الميدانية' : lang === 'fr' ? 'Articles, Communiqués et Événements' : 'Articles, Releases and Field News'}
            </h1>
            <p className="text-sm sm:text-base text-slate-600">
              {lang === 'ar' 
                ? 'تابع كافة الأنشطة، ورشات التأهيل المهني، قسم التعليم الأولي المكيف، وتدخلات الإدماج المدرسي وأخبار التوحد' 
                : lang === 'fr' 
                ? 'Découvrez toutes les activités, ateliers de réadaptation, classe adaptée et inclusion scolaire' 
                : 'Follow our activities, rehabilitation workshops, adapted preschool and school inclusion'}
            </p>
          </div>

          {/* Search and Category Filters */}
          <div className="bg-white p-4 sm:p-5 rounded-3xl border border-slate-200 shadow-sm flex flex-col sm:flex-row items-center justify-between gap-4">
            <div className="flex items-center gap-2 w-full sm:w-80 bg-slate-50 px-4 py-2.5 rounded-2xl border border-slate-200">
              <Search className="w-4 h-4 text-slate-400" />
              <input
                type="text"
                value={searchTerm}
                onChange={(e) => setSearchTerm(e.target.value)}
                placeholder={lang === 'ar' ? "ابحث في عناوين المقالات..." : lang === 'fr' ? "Rechercher dans les articles..." : "Search articles..."}
                className="w-full bg-transparent text-xs sm:text-sm border-0 focus:outline-none"
              />
            </div>

            <div className="flex items-center gap-1.5 overflow-x-auto w-full sm:w-auto pb-1">
              {categories.map(catKey => {
                const label = categoryLabels[catKey]?.[lang] || categoryLabels[catKey]?.ar || catKey;
                return (
                  <button
                    key={catKey}
                    onClick={() => setSelectedCategory(catKey)}
                    className={`px-3.5 py-2 rounded-xl text-xs font-bold transition whitespace-nowrap flex items-center gap-1 ${
                      selectedCategory === catKey
                        ? 'bg-emerald-700 text-white shadow-md'
                        : 'bg-slate-100 text-slate-700 hover:bg-slate-200'
                    }`}
                  >
                    {catKey === "أخبار وطنية (RSS)" && (
                      <span className="flex h-2 w-2 relative">
                        <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-emerald-400 opacity-75"></span>
                        <span className="relative inline-flex rounded-full h-2 w-2 bg-emerald-500"></span>
                      </span>
                    )}
                    <span>{label}</span>
                  </button>
                );
              })}
            </div>
          </div>

          {/* Interactive Screening Callout Banner */}
          <div className="bg-gradient-to-r from-emerald-900 via-teal-900 to-slate-900 rounded-3xl p-6 sm:p-8 text-white flex flex-col md:flex-row items-center justify-between gap-6 shadow-xl border border-emerald-700/40 relative overflow-hidden">
            <div className="absolute top-0 right-0 w-64 h-64 bg-emerald-500/10 rounded-full blur-3xl pointer-events-none" />
            <div className="space-y-2 text-center md:text-start relative z-10">
              <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-amber-400/20 text-amber-300 text-xs font-bold border border-amber-400/30">
                <Sparkles className="w-3.5 h-3.5 text-amber-400" />
                <span>{lang === 'ar' ? 'خدمة توجيهية مجانية للأسر' : lang === 'fr' ? 'Service d\'orientation gratuit' : 'Free Guidance Service'}</span>
              </div>
              <h2 className="text-xl sm:text-2xl font-black text-white">
                {lang === 'ar' ? 'هل تلاحظ تصرفات غير مألوفة لدى طفلك؟' : lang === 'fr' ? 'Remarquez-vous des signes chez votre enfant ?' : 'Notice unusual signs in your child?'}
              </h2>
              <p className="text-xs sm:text-sm text-emerald-100 max-w-2xl leading-relaxed">
                {lang === 'ar' 
                  ? 'أجب على 5 أسئلة استبيانية بسيطة واكتشف المؤشرات الأولية لطيف التوحد مع إمكانية التواصل الفوري مع أخصائيي AMSED بالقنيطرة عبر واتساب.' 
                  : lang === 'fr' 
                  ? 'Répondez à 5 questions rapides pour identifier les premiers signes et contactez nos spécialistes à Kénitra via WhatsApp.' 
                  : 'Answer 5 quick screening questions and connect immediately with AMSED Kenitra specialists on WhatsApp.'}
              </p>
            </div>
            <button
              onClick={() => setScreeningOpen(true)}
              className="bg-amber-400 hover:bg-amber-500 text-slate-950 font-black px-6 py-3.5 rounded-2xl shadow-lg hover:shadow-xl transition cursor-pointer text-xs sm:text-sm shrink-0 flex items-center gap-2 group relative z-10"
            >
              <span>{lang === 'ar' ? 'بدء استبيان المؤشرات (5 أسئلة)' : lang === 'fr' ? 'Lancer le test (5 questions)' : 'Start Screening (5 Questions)'}</span>
              <span className="group-hover:translate-x-1 transition">←</span>
            </button>
          </div>

          {/* Autism Screening Modal */}
          <AutismScreeningModal isOpen={screeningOpen} onClose={() => setScreeningOpen(false)} />

          {/* Articles Grid */}
          {filtered.length === 0 ? (
            <div className="bg-white rounded-3xl p-16 border border-slate-200 text-center text-slate-400">
              {lang === 'ar' ? 'لا توجد مقالات مطابقة لبحثك في هذا التصنيف.' : lang === 'fr' ? 'Aucun article ne correspond à votre recherche.' : 'No articles match your search in this category.'}
            </div>
          ) : (
            <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-8">
              {filtered.map(art => {
                // Ensure distinct matched image for each topic without repeated books/apple image
                const matchedImg = getTopicMatchedImage(art.title || art.title_ar || '', art.keywords);
                const displayImage = (art.image && !art.image.includes('photo-1503676260728')) 
                  ? art.image 
                  : matchedImg.url;

                const localizedTitle = getLocalized(art, 'title') || art.title;
                const localizedContent = getLocalized(art, 'content') || art.content || '';
                const categoryDisplay = categoryLabels[art.category]?.[lang] || art.category || 'AMSED';

                return (
                  <article
                    key={art.id}
                    className="bg-white rounded-3xl overflow-hidden border border-slate-200 shadow-sm hover:shadow-xl transition-all duration-300 flex flex-col justify-between group hover:-translate-y-1"
                  >
                    <div>
                      {/* Image */}
                      <div className="relative h-52 w-full bg-slate-100 overflow-hidden">
                        <img
                          src={displayImage}
                          alt={localizedTitle}
                          className="w-full h-full object-cover group-hover:scale-105 transition duration-500"
                          loading="lazy"
                          onError={(e) => {
                            e.target.onerror = null;
                            e.target.src = matchedImg.url;
                          }}
                        />
                        <div className="absolute top-3 start-3 flex items-center gap-1.5 flex-wrap">
                          <span className={`px-3 py-1 rounded-lg text-[11px] font-bold shadow ${
                            art.isRss 
                              ? 'bg-emerald-800 text-white' 
                              : 'bg-slate-900/80 text-white backdrop-blur-md'
                          }`}>
                            {categoryDisplay}
                          </span>
                          {(art.is_ai || art.autoGenerated || art.category === 'التوحد والطفولة') && (
                            <span className="px-2.5 py-1 rounded-lg text-[11px] font-bold shadow bg-emerald-800 text-amber-300 border border-amber-400/30 flex items-center gap-1">
                              <Sparkles className="w-3 h-3 text-amber-300" />
                              <span>{lang === 'ar' ? 'منشور معتمد • AMSED' : lang === 'fr' ? 'Publication AMSED' : 'AMSED Publication'}</span>
                            </span>
                          )}
                        </div>
                      </div>

                      {/* Content */}
                      <div className="p-6 space-y-3">
                        <div className="flex items-center gap-3 text-xs text-slate-400">
                          <span className="flex items-center gap-1">
                            <Calendar className="w-3.5 h-3.5" />
                            <span>{art.createdAt || art.created_at?.split('T')?.[0]}</span>
                          </span>
                          <span>•</span>
                          <span className="flex items-center gap-1">
                            <User className="w-3.5 h-3.5" />
                            <span>
                              {art.author && !art.author.includes('روبوت') 
                                ? art.author 
                                : (lang === 'ar' ? 'أطر جمعية AMSED' : lang === 'fr' ? 'Équipe AMSED' : 'AMSED Team')}
                            </span>
                          </span>
                        </div>

                        <h3 className="text-lg font-bold text-slate-900 group-hover:text-emerald-700 transition leading-snug line-clamp-2">
                          {art.isRss && art.link ? (
                            <a href={art.link} target="_blank" rel="noopener noreferrer">
                              {localizedTitle}
                            </a>
                          ) : (
                            <Link to={`/article/${art.id}`}>
                              {localizedTitle}
                            </Link>
                          )}
                        </h3>

                        <div 
                          className="text-xs sm:text-sm text-slate-600 line-clamp-3 leading-relaxed"
                          dangerouslySetInnerHTML={{ __html: localizedContent.replace(/<[^>]*>?/gm, '') }}
                        />
                      </div>
                    </div>

                    {/* Read More Footer */}
                    <div className="p-6 pt-0">
                      {art.isRss && art.link ? (
                        <a
                          href={art.link}
                          target="_blank"
                          rel="noopener noreferrer"
                          className="w-full inline-flex items-center justify-between bg-emerald-50 hover:bg-emerald-700 hover:text-white text-emerald-800 font-bold px-4 py-2.5 rounded-xl transition text-xs border border-emerald-200"
                        >
                          <span>{lang === 'ar' ? `قراءة في ${art.source || 'المصدر'}` : lang === 'fr' ? `Lire sur ${art.source || 'la source'}` : `Read on ${art.source || 'source'}`}</span>
                          <ExternalLink className="w-4 h-4" />
                        </a>
                      ) : (
                        <Link
                          to={`/article/${art.id}`}
                          className="w-full inline-flex items-center justify-between bg-slate-100 hover:bg-emerald-700 hover:text-white text-slate-700 font-bold px-4 py-2.5 rounded-xl transition text-xs"
                        >
                          <span>{lang === 'ar' ? 'قراءة المقال كاملاً' : lang === 'fr' ? "Lire l'article complet" : 'Read Full Article'}</span>
                          {dir === 'rtl' ? <ArrowLeft className="w-4 h-4" /> : <ArrowRight className="w-4 h-4" />}
                        </Link>
                      )}
                    </div>
                  </article>
                );
              })}
            </div>
          )}

        </div>
      </main>

      <Footer />
    </div>
  );
};

export default ArticlesPage;
