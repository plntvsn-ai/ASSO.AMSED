import React, { useState, useEffect, useRef, useCallback } from 'react';
import { Link } from 'react-router-dom';
import { useLanguage } from '../context/LanguageContext';
import { useData } from '../context/DataContext';
import { useCms } from '../context/CmsContext';
import { 
  Bell, Calendar, AlertCircle, ArrowLeft, ArrowRight, 
  X, Sparkles, Tag, ExternalLink, Radio,
  GraduationCap, BookOpen, Clock, ChevronRight, ChevronLeft,
  Award, HeartHandshake, Eye, CheckCircle2, Bookmark
} from 'lucide-react';

export const Announcements = () => {
  const { lang, dir, t, getLocalized } = useLanguage();
  const { data } = useData();
  const { cmsData } = useCms();
  const [activeFilter, setActiveFilter] = useState('all');
  const [selectedAnnouncement, setSelectedAnnouncement] = useState(null);
  const [rssNews, setRssNews] = useState([]);
  const [loadingRss, setLoadingRss] = useState(false);
  const [activeSlideIndex, setActiveSlideIndex] = useState(0);
  const [isPaused, setIsPaused] = useState(false);

  const carouselRef = useRef(null);

  // جلب الأخبار الحية من RSS
  useEffect(() => {
    const fetchNews = async () => {
      setLoadingRss(true);
      try {
        const res = await fetch('/api/news');
        if (res.ok) {
          const json = await res.json();
          const list = Array.isArray(json) ? json : (json?.news || []);
          if (list.length > 0) {
            setRssNews(list);
          }
        }
      } catch (err) {
        console.warn('Google News RSS notice:', err);
      } finally {
        setLoadingRss(false);
      }
    };

    fetchNews();
  }, []);

  const rawAnnouncements = data.announcements || [];

  const robotArticles = (cmsData?.articles || []).filter(
    a => a.is_ai || a.autoGenerated || a.category === 'التوحد والطفولة'
  );

  const formattedRobotItems = robotArticles.map((item, idx) => ({
    id: item.id || `robot-${idx}`,
    title: item.title,
    titleAr: item.title,
    titleFr: item.title_fr || item.title,
    titleEn: item.title_en || item.title,
    desc: item.excerpt || (item.content || '').slice(0, 160) + '...',
    descAr: item.excerpt || (item.content || '').slice(0, 160) + '...',
    descFr: item.excerpt || (item.content || '').slice(0, 160) + '...',
    descEn: item.excerpt || (item.content || '').slice(0, 160) + '...',
    date: item.createdAt || '2026-10-13',
    category: 'robot',
    image: item.image || 'https://images.unsplash.com/photo-1503676260728-1c00da094a0b?auto=format&fit=crop&w=900&q=80',
    source: item.author && !item.author.includes('روبوت') ? item.author : 'أطر جمعية AMSED',
    pedagogyTag: 'تأهيل وتربية خاصة',
    readingTime: '3 دقائق قراءة',
    isRobot: true,
    articleUrl: `/article/${item.id}`
  }));

  const formattedRssItems = rssNews.map((item, idx) => ({
    id: item.id || `rss-${idx}`,
    title: item.title,
    titleAr: item.title,
    titleFr: item.title,
    titleEn: item.title,
    desc: item.summary || item.rawTitle || item.title,
    descAr: item.summary || item.rawTitle || item.title,
    descFr: item.summary || item.rawTitle || item.title,
    descEn: item.summary || item.rawTitle || item.title,
    date: item.formattedDate || item.pubDate || 'مستجد اليوم',
    category: 'rss',
    image: item.image || 'https://images.unsplash.com/photo-1577896851231-70ef18881754?auto=format&fit=crop&w=900&q=80',
    source: item.source || 'رصد إعلامي',
    pedagogyTag: 'رصد إعلامي وطني',
    readingTime: 'دقيقتان',
    link: item.link,
    isRss: true
  }));

  const formattedAnnouncements = rawAnnouncements.map((item, idx) => ({
    ...item,
    id: item.id || `ann-${idx}`,
    pedagogyTag: item.category === 'urgent' ? 'بلاغ تربوي عاجل' : item.category === 'event' ? 'أنشطة وتأهيل ميداني' : 'مستجدات المؤسسة',
    readingTime: 'دقيقتان',
    source: 'إدارة التأهيل والتربية'
  }));

  // تجميع وتصفية القائمة
  let displayList = [];
  if (activeFilter === 'rss') {
    displayList = formattedRssItems;
  } else if (activeFilter === 'robots') {
    displayList = formattedRobotItems;
  } else if (activeFilter === 'all') {
    displayList = [
      ...formattedRobotItems.slice(0, 3), 
      ...formattedAnnouncements, 
      ...formattedRssItems.slice(0, 3)
    ];
  } else {
    displayList = formattedAnnouncements.filter(item => item.category === activeFilter);
  }

  // مضاعفة العناصر لضمان حركة مستمرة لا نهائية وسلسة بدون فراغ
  const loopedDisplayList = displayList.length > 2 ? [...displayList, ...displayList] : displayList;

  // إعادة ضبط التمرير للبداية عند تغيير الفلتر
  useEffect(() => {
    if (carouselRef.current) {
      carouselRef.current.scrollTo({ left: 0, behavior: 'smooth' });
      setActiveSlideIndex(0);
    }
  }, [activeFilter]);

  // تحديث مؤشر السلايد النشط عند التمرير
  const handleScroll = useCallback(() => {
    if (!carouselRef.current) return;
    const { scrollLeft } = carouselRef.current;
    const cardWidth = 390; // متوسط عرض البطاقة مع الهامش
    const scrollPos = Math.abs(scrollLeft);
    const index = Math.round(scrollPos / cardWidth) % (displayList.length || 1);
    setActiveSlideIndex(index);
  }, [displayList.length]);

  // التنقل: السابق والتالي مع مراعاة اتجاه اللغة RTL/LTR
  const scrollPrev = () => {
    if (!carouselRef.current) return;
    const scrollAmount = 390;
    const delta = dir === 'rtl' ? scrollAmount : -scrollAmount;
    carouselRef.current.scrollBy({ left: delta, behavior: 'smooth' });
  };

  const scrollNext = () => {
    if (!carouselRef.current) return;
    const scrollAmount = 390;
    const delta = dir === 'rtl' ? -scrollAmount : scrollAmount;
    carouselRef.current.scrollBy({ left: delta, behavior: 'smooth' });
  };

  const scrollToIndex = (idx) => {
    if (!carouselRef.current) return;
    const cardWidth = 390;
    const targetLeft = dir === 'rtl' ? -(idx * cardWidth) : (idx * cardWidth);
    carouselRef.current.scrollTo({ left: targetLeft, behavior: 'smooth' });
    setActiveSlideIndex(idx);
  };

  // حركة تلقائية حية ومستمرة تبدأ فور تحميل الصفحة وتتوقف عند التحويم
  useEffect(() => {
    const el = carouselRef.current;
    if (!el || displayList.length <= 1) return;

    let reqId;
    let lastTime = performance.now();
    const speed = 0.65; // بكسل في كل إطار - سرعة مريحة وانسيابية

    const step = (time) => {
      const dt = Math.min(time - lastTime, 50);
      lastTime = time;

      if (!isPaused && el) {
        const maxScroll = el.scrollWidth - el.clientWidth;
        if (maxScroll > 10) {
          const currentAbs = Math.abs(el.scrollLeft);

          if (currentAbs >= maxScroll - 5) {
            el.scrollLeft = 0;
          } else {
            if (dir === 'rtl') {
              if (el.scrollLeft <= 0) {
                el.scrollLeft -= speed * (dt / 16);
              } else {
                el.scrollLeft += speed * (dt / 16);
              }
            } else {
              el.scrollLeft += speed * (dt / 16);
            }
          }
        }
      }
      reqId = requestAnimationFrame(step);
    };

    reqId = requestAnimationFrame(step);
    return () => cancelAnimationFrame(reqId);
  }, [isPaused, displayList.length, dir]);

  const getCategoryBadge = (category, source) => {
    switch (category) {
      case 'robot':
        return {
          label: lang === 'ar' ? '🎓 مقال تربوي وتأهيلي (AMSED)' : lang === 'fr' ? '🎓 Article Éducatif (AMSED)' : '🎓 Educational Article (AMSED)',
          icon: <GraduationCap className="w-3.5 h-3.5" />,
          color: 'bg-gradient-to-r from-emerald-800 to-teal-900 text-amber-300 border-amber-400/40 shadow-sm'
        };
      case 'urgent':
        return {
          label: lang === 'ar' ? '🚨 بلاغ تربوي عاجل' : lang === 'fr' ? '🚨 Avis Urgent' : '🚨 Urgent Notice',
          icon: <AlertCircle className="w-3.5 h-3.5" />,
          color: 'bg-gradient-to-r from-rose-800 to-red-900 text-rose-100 border-rose-400/40 shadow-sm'
        };
      case 'event':
        return {
          label: lang === 'ar' ? '🎪 نشاط وقافلة تأهيلية' : lang === 'fr' ? '🎪 Activité & Caravane' : '🎪 Event & Outreach',
          icon: <Award className="w-3.5 h-3.5" />,
          color: 'bg-gradient-to-r from-amber-700 to-yellow-800 text-amber-100 border-amber-300/40 shadow-sm'
        };
      case 'rss':
        return {
          label: lang === 'ar' ? `📡 رصد وطني • ${source || 'Google News'}` : `📡 Presse • ${source || 'Google News'}`,
          icon: <Radio className="w-3.5 h-3.5 animate-pulse text-emerald-300" />,
          color: 'bg-gradient-to-r from-emerald-900 to-cyan-950 text-cyan-200 border-cyan-400/40 shadow-sm'
        };
      default:
        return {
          label: lang === 'ar' ? '📜 نشرة المؤسسة التربوية' : lang === 'fr' ? '📜 Communiqué Officiel' : '📜 Official Release',
          icon: <BookOpen className="w-3.5 h-3.5" />,
          color: 'bg-gradient-to-r from-slate-800 to-emerald-950 text-emerald-200 border-emerald-400/40 shadow-sm'
        };
    }
  };

  const ArrowIcon = dir === 'rtl' ? ArrowLeft : ArrowRight;

  return (
    <section 
      id="announcements" 
      className="relative py-20 overflow-hidden bg-gradient-to-b from-[#faf6ee] via-[#f7f2e7] to-[#f4ede0] border-b border-amber-200/60"
      onMouseEnter={() => setIsPaused(true)}
      onMouseLeave={() => setIsPaused(false)}
      onTouchStart={() => setIsPaused(true)}
      onTouchEnd={() => setIsPaused(false)}
    >
      {/* خلفية بنقوش الزليج والزخرفة المغربية الأصيلة (Moroccan Zellij Watermark) */}
      <div className="absolute inset-0 pointer-events-none opacity-[0.035] bg-[radial-gradient(#0d5938_1.5px,transparent_1.5px)] [background-size:20px_20px]" />
      
      {/* زخرفة هندسية مغربية علوية وسفلية خفيفة */}
      <div className="absolute top-0 inset-x-0 h-1.5 bg-gradient-to-r from-emerald-800 via-amber-400 to-emerald-800 opacity-80" />

      <div className="max-w-[1520px] mx-auto px-4 sm:px-6 lg:px-8 relative z-10">
        
        {/* ترويسة بطابع مغربي أصيل ومؤسسة تربوية */}
        <div className="text-center max-w-4xl mx-auto mb-10">
          
          {/* الشارة الرسمية المغربية */}
          <div className="inline-flex items-center gap-2.5 px-4 py-1.5 rounded-full bg-emerald-900 text-amber-300 text-xs font-bold mb-4 border border-amber-400/50 shadow-md">
            <span className="text-amber-400 text-sm">۞</span>
            <span>
              {lang === 'ar' 
                ? 'المملكة المغربية • فضاء الإعلام والتواصل التربوي' 
                : lang === 'fr' 
                ? 'Royaume du Maroc • Espace Média & Communication' 
                : 'Kingdom of Morocco • Media & Educational Outreach'}
            </span>
            <span className="text-amber-400 text-sm">۞</span>
          </div>

          {/* العنوان الرئيسي بخط أنيق مستوحى من المؤسسات التربوية الكبرى */}
          <h2 className="text-3xl sm:text-4xl lg:text-5xl font-black text-emerald-950 tracking-tight leading-tight">
            {t('announcements', 'title') || 'نافذة المستجدات والإعلانات التربوية'}
          </h2>

          {/* فاصل الزخرفة المغربية التقليدية (Moroccan Architectural Flourish) */}
          <div className="flex items-center justify-center gap-3 my-4">
            <div className="h-px w-16 sm:w-28 bg-gradient-to-r from-transparent via-amber-400 to-amber-600"></div>
            <span className="text-amber-600 font-serif text-sm tracking-widest flex items-center gap-1.5">
              <span>✦</span>
              <span className="text-base text-emerald-900 font-bold">۞</span>
              <span>✦</span>
            </span>
            <div className="h-px w-16 sm:w-28 bg-gradient-to-l from-transparent via-amber-400 to-amber-600"></div>
          </div>

          <p className="text-slate-700 text-sm sm:text-base lg:text-lg leading-relaxed max-w-3xl mx-auto font-medium">
            {t('announcements', 'subtitle') || 'مواكبة توثيقية حية لمسارات التأهيل، ورشات الإدماج المدرسي، وبحوث التوحد، مع تغطية مستمرة لكافة أنشطة الجمعية الميدانية بالقنيطرة والمغرب.'}
          </p>

          {/* شريط الأخبار الحية RSS بتصميم مغربي مذهب */}
          {rssNews.length > 0 && (
            <div className="mt-5 inline-flex items-center gap-2.5 px-4 py-2 bg-white/90 text-emerald-950 border border-amber-300/80 rounded-2xl text-xs sm:text-sm font-semibold max-w-2xl mx-auto shadow-sm backdrop-blur-sm">
              <span className="flex h-2.5 w-2.5 relative flex-shrink-0">
                <span className="animate-ping absolute inline-flex h-full w-full rounded-full bg-emerald-400 opacity-75"></span>
                <span className="relative inline-flex rounded-full h-2.5 w-2.5 bg-emerald-600"></span>
              </span>
              <span className="font-extrabold text-emerald-900 whitespace-nowrap flex items-center gap-1">
                <span>{lang === 'ar' ? '📡 رصد إخباري وطني:' : '📡 Presse:'}</span>
              </span>
              <span className="truncate text-slate-800">{rssNews[0]?.title}</span>
              <span className="text-[11px] bg-amber-100 text-amber-900 font-bold px-2 py-0.5 rounded border border-amber-200 flex-shrink-0">
                {rssNews[0]?.source}
              </span>
            </div>
          )}

          {/* تبويبات الفلترة بتصميم فاخر مستوحى من الأوسمة التربوية */}
          <div className="flex flex-wrap items-center justify-center gap-2 sm:gap-2.5 mt-8">
            <button
              onClick={() => setActiveFilter('all')}
              className={`px-4 py-2 rounded-xl text-xs sm:text-sm font-bold transition-all duration-200 flex items-center gap-1.5 ${
                activeFilter === 'all'
                  ? 'bg-emerald-900 text-amber-300 shadow-md border border-amber-400/60 scale-105'
                  : 'bg-white/80 text-emerald-950 hover:bg-white border border-amber-200/80 shadow-sm'
              }`}
            >
              <span>{lang === 'ar' ? 'جميع المستجدات' : lang === 'fr' ? 'Toutes les actualités' : 'All Updates'}</span>
              <span className="text-[10px] bg-amber-400/20 px-1.5 py-0.2 rounded-full">
                {formattedRobotItems.length + rawAnnouncements.length + (rssNews.length > 0 ? 3 : 0)}
              </span>
            </button>

            <button
              onClick={() => setActiveFilter('robots')}
              className={`px-4 py-2 rounded-xl text-xs sm:text-sm font-bold transition-all duration-200 flex items-center gap-1.5 ${
                activeFilter === 'robots'
                  ? 'bg-emerald-900 text-amber-300 shadow-md border border-amber-400/60 scale-105'
                  : 'bg-white/80 text-emerald-950 hover:bg-white border border-amber-200/80 shadow-sm'
              }`}
            >
              <GraduationCap className="w-4 h-4 text-amber-500" />
              <span>
                {lang === 'ar' 
                  ? `مقالات وبحوث تربوية (${formattedRobotItems.length})` 
                  : lang === 'fr' 
                  ? `Articles & Recherches (${formattedRobotItems.length})` 
                  : `Educational Articles (${formattedRobotItems.length})`}
              </span>
            </button>

            <button
              onClick={() => setActiveFilter('urgent')}
              className={`px-4 py-2 rounded-xl text-xs sm:text-sm font-bold transition-all duration-200 flex items-center gap-1.5 ${
                activeFilter === 'urgent'
                  ? 'bg-rose-900 text-rose-100 shadow-md border border-rose-400/60 scale-105'
                  : 'bg-white/80 text-rose-950 hover:bg-rose-50/80 border border-rose-200/80 shadow-sm'
              }`}
            >
              <AlertCircle className="w-3.5 h-3.5 text-rose-500" />
              <span>{t('announcements', 'urgent')}</span>
            </button>

            <button
              onClick={() => setActiveFilter('event')}
              className={`px-4 py-2 rounded-xl text-xs sm:text-sm font-bold transition-all duration-200 flex items-center gap-1.5 ${
                activeFilter === 'event'
                  ? 'bg-amber-800 text-amber-100 shadow-md border border-amber-400 scale-105'
                  : 'bg-white/80 text-amber-950 hover:bg-amber-50 border border-amber-200/80 shadow-sm'
              }`}
            >
              <Award className="w-3.5 h-3.5 text-amber-600" />
              <span>{lang === 'ar' ? 'أنشطة وقوافل' : lang === 'fr' ? 'Événements & Caravanes' : 'Events & Caravans'}</span>
            </button>

            <button
              onClick={() => setActiveFilter('news')}
              className={`px-4 py-2 rounded-xl text-xs sm:text-sm font-bold transition-all duration-200 flex items-center gap-1.5 ${
                activeFilter === 'news'
                  ? 'bg-emerald-900 text-amber-300 shadow-md border border-amber-400/60 scale-105'
                  : 'bg-white/80 text-emerald-950 hover:bg-white border border-amber-200/80 shadow-sm'
              }`}
            >
              <BookOpen className="w-3.5 h-3.5 text-emerald-600" />
              <span>{lang === 'ar' ? 'أخبار الجمعية' : lang === 'fr' ? 'Actualités AMSED' : 'Association News'}</span>
            </button>

            <button
              onClick={() => setActiveFilter('rss')}
              className={`px-4 py-2 rounded-xl text-xs sm:text-sm font-bold transition-all duration-200 flex items-center gap-1.5 ${
                activeFilter === 'rss'
                  ? 'bg-teal-900 text-cyan-200 shadow-md border border-cyan-400/60 scale-105'
                  : 'bg-white/80 text-teal-950 hover:bg-teal-50 border border-teal-200/80 shadow-sm'
              }`}
            >
              <Radio className="w-3.5 h-3.5 text-teal-600 animate-pulse" />
              <span>{lang === 'ar' ? 'رصد وطني حام (RSS)' : lang === 'fr' ? 'Presse Nationale (RSS)' : 'National Press (RSS)'}</span>
              {rssNews.length > 0 && (
                <span className="text-[10px] bg-teal-100 text-teal-900 px-1.5 py-0.5 rounded-full font-mono font-bold">
                  {rssNews.length}
                </span>
              )}
            </button>
          </div>
        </div>

        {/* أزرار التحكم بالكاروسيل في الأعلى والشريط التوجيهي */}
        <div className="flex items-center justify-between mb-5 px-2">
          {/* عداد المقالات المعروضة مع أيقونة تربوية */}
          <div className="flex items-center gap-2 text-xs sm:text-sm font-bold text-emerald-950 bg-white/70 px-3.5 py-1.5 rounded-xl border border-amber-200/70 shadow-sm">
            <Bookmark className="w-4 h-4 text-amber-600" />
            <span>
              {lang === 'ar' ? `عرض ${displayList.length} مستجدات تربوية` : lang === 'fr' ? `${displayList.length} actualités` : `${displayList.length} updates`}
            </span>
            <span className="text-[11px] text-amber-700 font-mono">
              ({activeSlideIndex + 1} / {displayList.length})
            </span>
          </div>

          {/* أزرار التنقل الأفقي بالأسهم ذات الطابع المغربي النحاسي */}
          <div className="flex items-center gap-2">
            <button
              onClick={scrollPrev}
              aria-label="السابق"
              className="w-10 h-10 sm:w-11 sm:h-11 rounded-full bg-white hover:bg-emerald-900 text-emerald-950 hover:text-amber-300 border-2 border-amber-300/80 hover:border-amber-400 flex items-center justify-center shadow-md hover:shadow-xl transition-all duration-200 active:scale-95 group"
            >
              {dir === 'rtl' ? (
                <ChevronRight className="w-5 h-5 group-hover:scale-110 transition-transform" />
              ) : (
                <ChevronLeft className="w-5 h-5 group-hover:scale-110 transition-transform" />
              )}
            </button>

            <button
              onClick={scrollNext}
              aria-label="التالي"
              className="w-10 h-10 sm:w-11 sm:h-11 rounded-full bg-white hover:bg-emerald-900 text-emerald-950 hover:text-amber-300 border-2 border-amber-300/80 hover:border-amber-400 flex items-center justify-center shadow-md hover:shadow-xl transition-all duration-200 active:scale-95 group"
            >
              {dir === 'rtl' ? (
                <ChevronLeft className="w-5 h-5 group-hover:scale-110 transition-transform" />
              ) : (
                <ChevronRight className="w-5 h-5 group-hover:scale-110 transition-transform" />
              )}
            </button>
          </div>
        </div>

        {/* الكاروسيل الأفقي (Horizontal Carousel Track) */}
        {displayList.length === 0 ? (
          <div className="text-center py-16 bg-white/90 rounded-3xl border border-amber-200/80 max-w-md mx-auto shadow-sm">
            <BookOpen className="w-10 h-10 text-amber-600 mx-auto mb-3 opacity-60" />
            <p className="text-slate-600 font-bold">
              {loadingRss ? (lang === 'ar' ? 'جارٍ جلب المستجدات...' : 'Chargement...') : t('announcements', 'noAnnouncements')}
            </p>
          </div>
        ) : (
          <div
            ref={carouselRef}
            onScroll={handleScroll}
            className="flex gap-5 sm:gap-6 overflow-x-auto pb-6 pt-2 px-1 sm:px-2 [scrollbar-width:none] [-ms-overflow-style:none] [&::-webkit-scrollbar]:hidden"
            style={{ WebkitOverflowScrolling: 'touch' }}
          >
            {loopedDisplayList.map((item, idx) => {
              const badge = getCategoryBadge(item.category, item.source);
              const title = getLocalized(item, 'title');
              const desc = getLocalized(item, 'desc');

              return (
                <article
                  key={`${item.id}-${idx}`}
                  className="w-[290px] sm:w-[340px] md:w-[370px] lg:w-[395px] shrink-0 group bg-gradient-to-b from-white via-[#fcfbf9] to-[#fbf8f2] rounded-[2rem] overflow-hidden border-2 border-amber-200/70 hover:border-amber-400/90 shadow-md hover:shadow-2xl transition-all duration-300 flex flex-col justify-between hover:-translate-y-1.5"
                >
                  {/* رأس البطاقة مع صورة داخل قوس مغربي تقليدي (Moroccan Arched Image Frame) */}
                  <div>
                    <div className="relative aspect-[16/10] w-full overflow-hidden bg-slate-900 border-b-2 border-amber-300/60">
                      <img
                        src={(item.image && !item.image.includes('542601906990-b4d3fb778b09') && !item.image.includes('picsum.photos')) ? item.image : "https://images.unsplash.com/photo-1503676260728-1c00da094a0b?auto=format&fit=crop&w=900&q=80"}
                        alt={title}
                        className="w-full h-full object-cover transition-transform duration-700 group-hover:scale-108"
                        loading="lazy"
                      />
                      
                      {/* طبقة تدرج لوني مع وسم الفئة */}
                      <div className="absolute inset-0 bg-gradient-to-t from-slate-950/80 via-transparent to-black/20 pointer-events-none" />

                      {/* شارة الفئة المذهبة على الصورة */}
                      <div className="absolute top-3 start-3 end-3 flex items-center justify-between gap-2">
                        <span className={`inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-[11px] font-bold border backdrop-blur-md ${badge.color}`}>
                          {badge.icon}
                          <span>{badge.label}</span>
                        </span>

                        {/* ختم أو نجمة مغربية خفيفة */}
                        <span className="w-6 h-6 rounded-full bg-white/20 backdrop-blur-md border border-white/40 flex items-center justify-center text-amber-300 text-xs shadow-inner">
                          ۞
                        </span>
                      </div>

                      {/* الوسم التربوي الملحق أسفل الصورة */}
                      <div className="absolute bottom-2.5 start-3 end-3 flex items-center justify-between text-[11px] text-white/90">
                        <span className="bg-emerald-950/85 px-2.5 py-0.5 rounded-md font-semibold border border-emerald-500/40 backdrop-blur-sm">
                          {item.pedagogyTag || (lang === 'ar' ? 'رعاية وتأهيل' : 'Rééducation')}
                        </span>
                        <span className="bg-black/60 px-2 py-0.5 rounded-md font-mono flex items-center gap-1 text-[10px] text-amber-200">
                          <Clock className="w-3 h-3 text-amber-300" />
                          <span>{item.readingTime || (lang === 'ar' ? '3 دقائق' : '3 min')}</span>
                        </span>
                      </div>
                    </div>

                    {/* جسم البطاقة بمظهر وثائقي تربوي */}
                    <div className="p-5 sm:p-6 pb-2 text-start">
                      {/* التاريخ والمصدر الميداني */}
                      <div className="flex items-center justify-between text-xs text-slate-500 mb-3 border-b border-amber-100/80 pb-2.5">
                        <div className="flex items-center gap-1.5 text-emerald-900 font-semibold">
                          <Calendar className="w-3.5 h-3.5 text-amber-600" />
                          <time dateTime={item.date}>{item.date}</time>
                        </div>
                        {item.source && (
                          <span className="font-bold text-[11px] text-emerald-950 bg-emerald-50 px-2.5 py-0.5 rounded-full border border-emerald-200/80 truncate max-w-[140px]">
                            {item.source}
                          </span>
                        )}
                      </div>

                      {/* عنوان المقال بخط عريض ورصين */}
                      <h3 className="text-base sm:text-lg font-extrabold text-slate-900 group-hover:text-emerald-900 transition leading-snug line-clamp-2 min-h-[3rem]">
                        {title}
                      </h3>

                      {/* مقتطف المحتوى الإرشادي والتربوي */}
                      <p className="mt-2.5 text-xs sm:text-sm text-slate-600 line-clamp-3 leading-relaxed">
                        {desc}
                      </p>
                    </div>
                  </div>

                  {/* تذييل البطاقة مع أزرار الإجراء التربوي */}
                  <div className="p-5 sm:p-6 pt-3 mt-1 border-t border-amber-200/50 flex items-center justify-between bg-amber-50/30 rounded-b-[2rem]">
                    {item.isRobot && item.articleUrl ? (
                      <Link
                        to={item.articleUrl}
                        className="inline-flex items-center gap-1.5 text-xs sm:text-sm font-black text-emerald-950 hover:text-amber-700 transition group/btn"
                      >
                        <span className="border-b border-emerald-900 group-hover/btn:border-amber-600 pb-0.5">
                          {lang === 'ar' ? 'قراءة المقال كاملاً' : lang === 'fr' ? "Lire l'article complet" : 'Read full article'}
                        </span>
                        <ArrowIcon className="w-4 h-4 text-amber-600 group-hover/btn:translate-x-1 transition-transform" />
                      </Link>
                    ) : item.isRss && item.link ? (
                      <a
                        href={item.link}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="inline-flex items-center gap-1.5 text-xs sm:text-sm font-black text-teal-900 hover:text-teal-700 transition"
                      >
                        <span>
                          {lang === 'ar' ? `قراءة في ${item.source || 'المصدر'}` : lang === 'fr' ? `Lire sur ${item.source || 'la source'}` : `Read on ${item.source || 'source'}`}
                        </span>
                        <ExternalLink className="w-3.5 h-3.5 text-teal-600" />
                      </a>
                    ) : (
                      <button
                        onClick={() => setSelectedAnnouncement(item)}
                        className="inline-flex items-center gap-1.5 text-xs sm:text-sm font-black text-emerald-950 hover:text-amber-700 transition group/btn"
                      >
                        <span className="border-b border-emerald-900 group-hover/btn:border-amber-600 pb-0.5">
                          {lang === 'ar' ? 'تفاصيل الإعلان التربوي' : lang === 'fr' ? "Détails de l'annonce" : 'Announcement details'}
                        </span>
                        <ArrowIcon className="w-4 h-4 text-amber-600 group-hover/btn:translate-x-1 transition-transform" />
                      </button>
                    )}

                    {/* شارة إضافية للحالات المستعجلة */}
                    {item.category === 'urgent' && (
                      <a
                        href="#contact"
                        className="text-[11px] bg-gradient-to-r from-emerald-800 to-emerald-900 hover:from-emerald-900 hover:to-emerald-950 text-amber-300 font-extrabold px-3 py-1.5 rounded-xl border border-amber-400/50 shadow-sm transition"
                      >
                        {lang === 'ar' ? 'تواصل للاستفسار' : lang === 'fr' ? 'Contact' : 'Inquire'}
                      </a>
                    )}
                  </div>
                </article>
              );
            })}
          </div>
        )}

        {/* مؤشرات التنقل السفلية (Carousel Pagination Dots) */}
        {displayList.length > 1 && (
          <div className="flex items-center justify-center gap-1.5 mt-8">
            {displayList.map((_, idx) => (
              <button
                key={`dot-${idx}`}
                onClick={() => scrollToIndex(idx)}
                aria-label={`الانتقال إلى المستجد رقم ${idx + 1}`}
                className={`transition-all duration-300 rounded-full ${
                  idx === activeSlideIndex
                    ? 'w-8 h-2.5 bg-gradient-to-r from-emerald-800 to-amber-500 shadow-md border border-amber-300'
                    : 'w-2.5 h-2.5 bg-amber-300/80 hover:bg-amber-400'
                }`}
              />
            ))}
          </div>
        )}

        {/* دعوة ورابط للانتقال إلى المكتبة الكاملة للمقالات */}
        <div className="mt-12 text-center">
          <Link
            to="/articles"
            className="inline-flex items-center gap-3 px-7 py-3.5 rounded-2xl bg-gradient-to-r from-emerald-900 via-[#0a4a3a] to-emerald-900 text-amber-300 font-black text-sm sm:text-base border-2 border-amber-400/60 shadow-xl hover:shadow-2xl hover:scale-[1.02] transition-all duration-300 group"
          >
            <BookOpen className="w-5 h-5 text-amber-400" />
            <span>
              {lang === 'ar' 
                ? 'تصفح المكتبة التربوية الشاملة لجميع المقالات والبحوث والأخبار' 
                : lang === 'fr' 
                ? 'Explorer la bibliothèque éducative des articles et actualités' 
                : 'Browse the full educational library of articles and news'}
            </span>
            <ArrowIcon className="w-4 h-4 text-amber-300 group-hover:translate-x-1 transition-transform" />
          </Link>
        </div>

      </div>

      {/* نافذة المعاينة الكاملة للمقال أو الإعلان (Pedagogical Modal) */}
      {selectedAnnouncement && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/75 backdrop-blur-md animate-fadeIn">
          <div className="bg-gradient-to-b from-white via-[#faf8f4] to-[#f6f1e8] rounded-[2.5rem] max-w-2xl w-full max-h-[90vh] overflow-y-auto shadow-2xl border-2 border-amber-300/80 relative">
            
            {/* زر الإغلاق المذهب */}
            <button
              onClick={() => setSelectedAnnouncement(null)}
              className="absolute top-4 end-4 z-20 p-2.5 bg-slate-900/80 hover:bg-slate-900 text-amber-300 rounded-full transition shadow-lg border border-amber-400/40"
              aria-label="إغلاق النافذة"
            >
              <X className="w-5 h-5" />
            </button>

            {/* صورة الإعلان مع إطار القوس المغربي */}
            {selectedAnnouncement.image && (
              <div className="relative h-64 w-full overflow-hidden rounded-t-[2.5rem] border-b-2 border-amber-400/60">
                <img
                  src={selectedAnnouncement.image}
                  alt={selectedAnnouncement.isRss ? selectedAnnouncement.title : getLocalized(selectedAnnouncement, 'title')}
                  className="w-full h-full object-cover"
                />
                <div className="absolute inset-0 bg-gradient-to-t from-black/70 via-transparent to-transparent pointer-events-none" />
                <div className="absolute bottom-4 start-4 end-4 flex items-center justify-between text-white text-xs">
                  <span className="bg-emerald-950/90 text-amber-300 px-3 py-1 rounded-full font-bold border border-amber-400/40">
                    {selectedAnnouncement.pedagogyTag || (lang === 'ar' ? 'إعلان تربوي' : 'Actualité')}
                  </span>
                  <span className="font-mono text-amber-200">
                    {selectedAnnouncement.date}
                  </span>
                </div>
              </div>
            )}

            <div className="p-6 sm:p-8 space-y-5 text-start">
              <div className="flex items-center justify-between gap-2 border-b border-amber-200/80 pb-3">
                <span className={`px-3 py-1 rounded-full text-xs font-bold border ${getCategoryBadge(selectedAnnouncement.category, selectedAnnouncement.source).color}`}>
                  {getCategoryBadge(selectedAnnouncement.category, selectedAnnouncement.source).label}
                </span>
                <span className="text-xs text-emerald-950 font-bold flex items-center gap-1">
                  <Calendar className="w-3.5 h-3.5 text-amber-600" />
                  {selectedAnnouncement.date}
                </span>
              </div>

              <h3 className="text-xl sm:text-2xl font-black text-slate-900 leading-snug">
                {selectedAnnouncement.isRss ? selectedAnnouncement.title : getLocalized(selectedAnnouncement, 'title')}
              </h3>

              <div className="text-slate-700 leading-relaxed whitespace-pre-line text-sm sm:text-base border-t border-b border-amber-200/60 py-4 bg-white/60 p-4 rounded-2xl">
                {selectedAnnouncement.isRss ? selectedAnnouncement.desc : getLocalized(selectedAnnouncement, 'desc')}
              </div>

              {/* أزرار الإجراء في النافذة */}
              <div className="flex flex-wrap items-center justify-end gap-3 pt-2">
                {selectedAnnouncement.isRss && selectedAnnouncement.link ? (
                  <a
                    href={selectedAnnouncement.link}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="inline-flex items-center gap-2 bg-emerald-900 hover:bg-emerald-950 text-amber-300 px-6 py-2.5 rounded-xl text-sm font-black transition shadow-lg border border-amber-400/60"
                  >
                    <span>
                      {lang === 'ar' ? `فتح في ${selectedAnnouncement.source || 'المصدر الأصلي'}` : lang === 'fr' ? `Ouvrir sur ${selectedAnnouncement.source || 'la source'}` : `Open on ${selectedAnnouncement.source || 'source'}`}
                    </span>
                    <ExternalLink className="w-4 h-4 text-amber-400" />
                  </a>
                ) : (
                  <a
                    href="#contact"
                    onClick={() => setSelectedAnnouncement(null)}
                    className="bg-emerald-900 hover:bg-emerald-950 text-amber-300 px-6 py-2.5 rounded-xl text-sm font-black transition shadow-lg border border-amber-400/60"
                  >
                    {t('nav', 'contact')}
                  </a>
                )}
                
                <button
                  onClick={() => setSelectedAnnouncement(null)}
                  className="bg-amber-100/80 hover:bg-amber-200 text-amber-950 px-5 py-2.5 rounded-xl text-sm font-bold transition border border-amber-300/80"
                >
                  {t('announcements', 'closeModal')}
                </button>
              </div>
            </div>
          </div>
        </div>
      )}
    </section>
  );
};
